function buildAccounts(): { accounts: Account[]; contacts: Contact[] } {
  const accounts: Account[] = [];
  const contacts: Contact[] = [];

  for (const row of rawAccounts) {
    const buyerId = `${row.id}-buyer`;
    accounts.push({
      id: row.id,
      company: row.company,
      domain: row.domain,
      industry: row.industry,
      stage: row.stage,
      score: row.score,
      owner: row.owner,
      state: row.state,
      reason: row.reason,
      nextAction: row.nextAction,
      dueAt: hoursFromNow(row.dueHours),
      whyNow: row.whyNow,
      whyNowSource: {
        label: row.sourceLabel,
        href: row.sourceHref,
        field: "whyNow",
      },
      buyerId,
      highValue: row.highValue,
    });
    contacts.push({
      id: buyerId,
      accountId: row.id,
      name: row.buyer,
      title: row.title,
      email: row.email,
      rationale: row.rationale,
      isBuyer: true,
    });
    row.others?.forEach((person, index) => {
      contacts.push({
        id: `${row.id}-p${index}`,
        accountId: row.id,
        name: person.name,
        title: person.title,
        rationale: "Also at the company.",
        isBuyer: false,
      });
    });
  }

  return { accounts, contacts };
}

